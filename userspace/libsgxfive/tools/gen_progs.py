"""Generate src/prog_asm_gen.h: the transfer programs of libsgxfive's assembled source.

Assembles asm/transfer/ (tools/fwcutter/ours.py runs usse-asm and pds-asm) and
writes the words as C arrays, each commented with its instruction, plus the TQ_META and
TQ_PATCHES records of tools/fwcutter/facts.py as C tables (design/sgx545_fw_format.md
§9-§11). The output is checked in; tests/test_prog_asm.py regenerates it and compares.

    usage: gen_progs.py [-o src/prog_asm_gen.h]
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent.parent
sys.path.insert(0, str(ROOT / "tools" / "fwcutter"))
import facts      # noqa: E402
import fwformat as F   # noqa: E402
import ours       # noqa: E402

HEAPS = {facts.PIXELSHADER: "DRM_SGXFIVE_HEAP_USSE_PIXEL",
         facts.PDSPIXEL: "DRM_SGXFIVE_HEAP_PDS_PIXEL"}
ENCODINGS = {F.ENC_WORD32: "PA_WORD32", F.ENC_USSE_LIMM: "PA_USSE_LIMM",
             F.ENC_EMITPIX_SB: "PA_EMITPIX_SB"}
KINDS = {F.K_CONST: "PA_CONST", F.K_ADDR: "PA_ADDR", F.K_PARAM: "PA_PARAM",
         F.K_DOUTU: "PA_DOUTU"}
PARAMS = ("COLOUR", "PBE0", "PBE1", "PBE2", "PBE3", "SIDEBAND", "T0", "T1", "SRC")


def prog(tid: int) -> str:
    return f"SGXFIVE_PROG_{facts.TQ_NAMES[tid]}"


def target(e: F.Expr) -> str:
    if e.kind == F.K_PARAM:
        return f"SGXFIVE_PARAM_{PARAMS[e.target]}"
    if e.kind in (F.K_ADDR, F.K_DOUTU):
        return prog(e.target)
    return "0"


def array(tid: int) -> list[str]:
    name, isa = ours.PROGS[tid]
    ctype, digits, suffix = ("uint64_t", 16, "ull") if isa == "usse" else ("uint32_t", 8, "")
    out = [f"/* {name}: {facts.TQ_NAMES[tid]} */",
           f"static const {ctype} {name[:-2]}[] = {{"]
    for word, text in ours.listing(tid):
        text = re.sub(r"\s*/\*.*?\*/", "", text)       # the optional /* incp */ notes
        out.append(f"\t0x{word:0{digits}x}{suffix},\t/* {text} */")
    return out + ["};", ""]


def generate() -> str:
    meta = {m.id: m for m in facts.TQ_META}
    # REUSE-IgnoreStart
    out = ["/* SPDX-License-Identifier: MIT */",  # REUSE-IgnoreEnd
           "/*",
           " * Generated by tools/gen_progs.py (make gen): do not edit. The transfer",
           " * programs of asm/transfer/, assembled, and the TQ_META and",
           " * TQ_PATCHES records of tools/fwcutter/facts.py (design/sgx545_fw_format.md",
           " * §9-§11). Included by src/prog_asm.c only.",
           " */",
           ""]
    for tid in sorted(ours.PROGS):
        out += array(tid)
    out.append("static const struct prog_asm progs[SGXFIVE_PROG_COUNT] = {")
    for tid in sorted(ours.PROGS):
        m, (name, isa) = meta[tid], ours.PROGS[tid]
        flags = "SGXFIVE_PROG_NO_STRADDLE" if m.flags == F.TQ_NO_STRADDLE else str(m.flags)
        if m.flags not in (0, F.TQ_NO_STRADDLE):
            raise SystemExit(f"template {tid}: unknown flags {m.flags:#x}")
        out += [f"\t[{prog(tid)}] = {{",
                f"\t\t.meta = {{ {HEAPS[m.heap]}, {m.temps}, {m.pds_attrs}, {m.size:#x}, "
                f"{m.align}, {m.pds_data:#x}, {flags} }},",
                f"\t\t.{isa} = {name[:-2]}, .count = ARRAY_SIZE({name[:-2]}),",
                "\t},"]
    out += ["};", "", "/* Applied in this order (format §9.4). */",
            "static const struct prog_asm_patch patches[] = {"]
    for e in facts.TQ_PATCHES:
        if e.kind not in KINDS or e.encoding not in ENCODINGS or e.param:
            raise SystemExit(f"cannot express {e} in the C tables")
        out.append(f"\t{{ {prog(e.buffer)}, {ENCODINGS[e.encoding]}, {KINDS[e.kind]}, "
                   f"{target(e)}, {e.offset}, {e.addend:#x} }},")
    return "\n".join(out + ["};", ""])


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="gen_progs.py", description=__doc__.splitlines()[0])
    ap.add_argument("-o", "--output", help="write here instead of standard output")
    args = ap.parse_args(argv)
    text = generate()
    if args.output:
        pathlib.Path(args.output).write_text(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
