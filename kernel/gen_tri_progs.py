"""Generate kernel/gma500/sgxfive/sgx_tri_progs.h: the first triangle's GPU programs.

Assembles our own sources in asm/tri/ and asm/transfer/ (with usse-asm and pds-asm, built on
demand) and writes the words as C arrays, each commented with its instruction, for the
debugfs triangle test (sgx_tri.c, design/sgx545_3d.md "First triangle"). The kernel patches
the fields these sources leave at 0 (DOUTU words, immediates, PBE words, phase addresses).
With --user it writes libsgxfive's copy instead (userspace/libsgxfive/src/tri_progs_gen.h,
MIT, stdint types, tri_ names), which the render engine patches the same way.
The outputs are checked in; test_gen_tri_progs.py regenerates them and compares.

    usage: gen_tri_progs.py [--user] [-o OUTPUT]
"""
from __future__ import annotations

import argparse
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
ASM_DIR = ROOT / "tools" / "usse-asm"
ASM_SRC = ROOT / "asm"
OUTPUT = ROOT / "kernel" / "gma500" / "sgxfive" / "sgx_tri_progs.h"
USER_OUTPUT = ROOT / "userspace" / "libsgxfive" / "src" / "tri_progs_gen.h"

# (source under asm/, ISA): the vertex side, then the pixel side (the transfer programs reused).
PROGS = [
    ("tri/pds_vtx.s", "pds"), ("tri/use_vtx.s", "usse"),
    ("tri/pds_mte.s", "pds"), ("tri/use_mtest18.s", "usse"), ("tri/use_mtest2.s", "usse"),
    ("transfer/pds_prim.s", "pds"), ("transfer/pds_sec.s", "pds"), ("transfer/use_fill.s", "usse"),
    ("transfer/use_sec.s", "usse"), ("transfer/pds_pixevent.s", "pds"), ("tri/use_ptoff.s", "usse"),
    ("transfer/use_eot.s", "usse"), ("transfer/use_eor.s", "usse"),
]
WORD = {"usse": 8, "pds": 4}

_built = False


def _tool(isa: str) -> pathlib.Path:
    global _built
    if not _built:
        r = subprocess.run(["make", "-s", "-C", str(ASM_DIR)], capture_output=True, text=True)
        if r.returncode:
            raise SystemExit(f"cannot build the assembler in {ASM_DIR}:\n{r.stderr}")
        _built = True
    return ASM_DIR / ("usse-asm" if isa == "usse" else "pds-asm")


def source(name: str) -> pathlib.Path:
    """A program under asm/: "tri/use_vtx.s", or a bare file name looked up in tri/ and transfer/."""
    for p in (ASM_SRC / name, ASM_SRC / "tri" / name, ASM_SRC / "transfer" / name):
        if p.is_file():
            return p
    raise SystemExit(f"{name}: no such program under {ASM_SRC}")


def listing(name: str, isa: str) -> list[tuple[int, str]]:
    """The program as (word, text) pairs; a PDS data dword reads "data"."""
    with tempfile.TemporaryDirectory() as d:
        out = pathlib.Path(d) / "out.bin"
        r = subprocess.run([str(_tool(isa)), "-l", "-o", str(out), str(source(name))],
                           capture_output=True, text=True)
        if r.returncode:
            raise SystemExit(f"{name}: {r.stderr.strip()}")
        raw = out.read_bytes()
    width = WORD[isa]
    words = [int.from_bytes(raw[i:i + width], "little") for i in range(0, len(raw), width)]
    texts = [line.split("\t", 1)[1].strip() for line in r.stdout.splitlines() if "\t" in line]
    if len(texts) != len(words):
        raise SystemExit(f"{name}: the listing does not match the binary")
    return list(zip(words, texts))


def cname(name: str, user: bool = False) -> str:
    return ("tri_" if user else "sgx_tri_") + pathlib.Path(name).stem


def array(name: str, isa: str, user: bool = False) -> list[str]:
    ctype, digits, suffix = ("u64", 16, "ull") if isa == "usse" else ("u32", 8, "")
    if user:
        ctype = "uint64_t" if isa == "usse" else "uint32_t"
    words = listing(name, isa)
    out = [f"/* {pathlib.Path(name).name} */", f"static const {ctype} {cname(name, user)}[] = {{"]
    for word, text in words:
        text = re.sub(r"\s*/\*.*?\*/", "", text)        # the optional /* incp */ notes
        out.append(f"\t0x{word:0{digits}x}{suffix},\t/* {text} */")
    out.append("};")
    if isa == "pds":
        data = sum(1 for _w, t in words if t == "data")
        out.append(f"#define {cname(name, user).upper()}_DATA\t{data}\t/* data dwords */")
    return out + [""]


def generate(user: bool = False) -> str:
    if user:
        # REUSE-IgnoreStart
        out = ["/* SPDX-License-Identifier: MIT */",  # REUSE-IgnoreEnd
               "/*",
               " * Generated by kernel/gen_tri_progs.py --user: do not edit.",
               " * The first triangle's programs (design/sgx545_3d.md, \"First triangle\"),",
               " * assembled from our own sources in asm/. The fields the",
               " * sources leave at 0 are patched by render.c. Included by render.c only.",
               " */",
               "#include <stdint.h>",
               ""]
    else:
        # REUSE-IgnoreStart
        out = ["/* SPDX-License-Identifier: GPL-2.0-only OR MIT */",  # REUSE-IgnoreEnd
               "/*",
               " * Generated by kernel/gen_tri_progs.py in the SGXhumation tree: do not edit.",
               " * The first triangle's programs (design/sgx545_3d.md, \"First triangle\"),",
               " * assembled from our own sources in asm/. The fields the",
               " * sources leave at 0 are patched by sgx_tri.c. Included by sgx_tri.c only.",
               " */",
               ""]
    for name, isa in PROGS:
        out += array(name, isa, user)
    return "\n".join(out)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="gen_tri_progs.py", description=__doc__.splitlines()[0])
    ap.add_argument("-o", "--output", help="write here instead of standard output")
    ap.add_argument("--user", action="store_true", help="libsgxfive's copy (MIT, stdint)")
    args = ap.parse_args(argv)
    text = generate(args.user)
    if args.output:
        pathlib.Path(args.output).write_text(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
