static inline const char *bridge_cmd_name(unsigned nr)
{
    const char *n = 0;
    unsigned ncore = sizeof BRIDGE_CORE_NAMES / sizeof BRIDGE_CORE_NAMES[0];
    unsigned nsgx = sizeof BRIDGE_SGX_NAMES / sizeof BRIDGE_SGX_NAMES[0];
    if (nr < ncore)
        n = BRIDGE_CORE_NAMES[nr];
    else if (nr >= BRIDGE_SGX_CMD_BASE && nr - BRIDGE_SGX_CMD_BASE < nsgx)
        n = BRIDGE_SGX_NAMES[nr - BRIDGE_SGX_CMD_BASE];
    return n ? n : "?";
}

